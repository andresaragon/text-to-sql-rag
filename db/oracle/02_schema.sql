ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE sales.customers (
    customer_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR2(150) NOT NULL,
    email           VARCHAR2(150) UNIQUE NOT NULL,
    country         VARCHAR2(50),
    created_at      TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE sales.invoices (
    invoice_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     NUMBER NOT NULL REFERENCES sales.customers(customer_id),
    amount          NUMBER(12, 2) NOT NULL,
    currency        VARCHAR2(3) DEFAULT 'USD',
    issued_date     DATE NOT NULL,
    due_date        DATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    CONSTRAINT check_invoice_status CHECK (status IN ('pending', 'paid', 'overdue'))
);

CREATE TABLE sales.payments (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      NUMBER NOT NULL REFERENCES sales.invoices(invoice_id),
    amount_paid     NUMBER(12, 2) NOT NULL,
    paid_at         TIMESTAMP NOT NULL,
    payment_method  VARCHAR2(30)
);

CREATE TABLE sales.collection_actions (
    action_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      NUMBER NOT NULL REFERENCES sales.invoices(invoice_id),
    action_type     VARCHAR2(30) NOT NULL,
    action_date     DATE NOT NULL,
    notes           VARCHAR2(4000)
);

GRANT SELECT ON sales.customers TO app_ro;
GRANT SELECT ON sales.invoices TO app_ro;
GRANT SELECT ON sales.payments TO app_ro;
GRANT SELECT ON sales.collection_actions TO app_ro;
